"""Unit tests for the ``requirements.txt`` vs ``uv export`` comparison (#2228).

Package, version, hashes and comments are compared exactly. Environment markers are compared
by semantic equivalence (uv 0.13 rewrites some markers algebraically; uv 0.11.2 wrote others).
"""

from __future__ import annotations

from pathlib import Path

import pytest

from tests.uv_export_compare import (
    diff_pylock_bodies,
    diff_requirements,
    markers_equivalent,
    normalize_uv_export_text,
)

REPO_ROOT = Path(__file__).resolve().parents[1]

# Measured: uv 0.11.2 vs uv 0.13.7 on this repo's uv.lock (the only marker that differs).
MSOFFCRYPTO_0112 = (
    "(platform_python_implementation != 'PyPy' and sys_platform == 'darwin') "
    "or (platform_python_implementation != 'PyPy' and sys_platform == 'win32') "
    "or (sys_platform != 'darwin' and sys_platform != 'win32')"
)
MSOFFCRYPTO_0137 = "platform_python_implementation != 'PyPy' or (sys_platform != 'darwin' and sys_platform != 'win32')"

HEADER = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv export --frozen --no-emit-project -o {out}\n"
)
BODY = (
    "alpha==1.0.0 \\\n"
    "    --hash=sha256:aaaa \\\n"
    "    --hash=sha256:bbbb\n"
    "    # via beta\n"
    f"msoffcrypto-tool==6.1.0 ; {MSOFFCRYPTO_0112} \\\n"
    "    --hash=sha256:cccc\n"
    "    # via gamma\n"
    "pywin32==311 ; sys_platform == 'win32' \\\n"
    "    --hash=sha256:dddd\n"
)


def _doc(body: str = BODY, out: str = "requirements.txt") -> str:
    return HEADER.format(out=out) + body


# --------------------------------------------------------------------------- markers


@pytest.mark.parametrize(
    ("a", "b"),
    [
        (MSOFFCRYPTO_0112, MSOFFCRYPTO_0137),
        ("python_full_version >= '3.10.0'", "python_full_version >= '3.10'"),
        ("sys_platform == 'win32'", 'sys_platform == "win32"'),
        (
            "sys_platform == 'win32' or os_name == 'nt'",
            "os_name == 'nt' or sys_platform == 'win32'",
        ),
        (
            "sys_platform == 'win32' and os_name == 'nt'",
            "os_name == 'nt' and sys_platform == 'win32'",
        ),
        (
            "sys_platform != 'darwin' and sys_platform != 'darwin'",
            "sys_platform != 'darwin'",
        ),
        (
            "python_version >= '3.10'",
            "python_version >= '3.10' and python_version >= '3.10'",
        ),
        (
            "sys_platform == 'linux' or sys_platform != 'linux'",
            "platform_python_implementation == 'PyPy' or platform_python_implementation != 'PyPy'",
        ),
    ],
)
def test_equivalent_markers(a: str, b: str) -> None:
    assert markers_equivalent(a, b)
    assert markers_equivalent(b, a)


@pytest.mark.parametrize(
    ("a", "b"),
    [
        ("sys_platform == 'win32'", "sys_platform != 'win32'"),
        # differs only on an unlisted platform value (needs the "other" candidate)
        (
            "sys_platform != 'darwin'",
            "sys_platform == 'linux' or sys_platform == 'win32'",
        ),
        # one clause of the measured pair dropped
        (
            MSOFFCRYPTO_0137,
            "platform_python_implementation != 'PyPy' or (sys_platform != 'darwin')",
        ),
        (MSOFFCRYPTO_0112, "sys_platform != 'darwin' and sys_platform != 'win32'"),
        # version boundary
        ("python_version >= '3.10'", "python_version >= '3.11'"),
        ("python_version < '3.12'", "python_version <= '3.12'"),
        # python_full_version carries a patch level: 3.9.5 is > 3.9 but < 3.10
        ("python_full_version >= '3.10'", "python_full_version > '3.9'"),
        ("python_full_version > '3.9.0'", "python_full_version >= '3.9.1'"),
        ("implementation_version >= '7.3'", "implementation_version > '7.2'"),
        # `in` / `not in` are substring tests; ordering on non-version variables is
        # lexicographic. Not provable with the candidate set: fail closed (B1).
        ("sys_platform == 'linux2'", "sys_platform in 'linux2'"),
        ("platform_machine != 'x86_64'", "platform_machine not in 'x86_64'"),
        ("platform_release > '4.9'", "platform_release >= '5.0'"),
        # different variable
        ("sys_platform == 'win32'", "os_name == 'nt'"),
        (
            "sys_platform == 'win32'",
            "sys_platform == 'win32' and python_version >= '3.9'",
        ),
    ],
)
def test_non_equivalent_markers(a: str, b: str) -> None:
    assert not markers_equivalent(a, b)
    assert not markers_equivalent(b, a)


def test_unparseable_marker_falls_back_to_exact_text() -> None:
    assert markers_equivalent("sys_platform ==", "sys_platform ==")
    assert not markers_equivalent("sys_platform ==", "sys_platform == 'win32'")


# --------------------------------------------------------------------------- requirements diff


def test_identical_documents_have_no_diff() -> None:
    assert diff_requirements(_doc(), _doc()) == []


def test_header_output_path_is_tolerated() -> None:
    fresh = _doc(out="/tmp/some/other/place.txt")
    assert diff_requirements(_doc(), fresh) == []
    assert normalize_uv_export_text(fresh) == normalize_uv_export_text(_doc())


def test_equivalent_marker_rewrite_is_tolerated() -> None:
    fresh = _doc(BODY.replace(MSOFFCRYPTO_0112, MSOFFCRYPTO_0137))
    assert diff_requirements(_doc(), fresh) == []


def test_version_change_is_detected() -> None:
    fresh = _doc(BODY.replace("alpha==1.0.0", "alpha==1.0.1"))
    problems = diff_requirements(_doc(), fresh)
    assert problems
    assert any("alpha" in p for p in problems)


def test_version_change_hidden_behind_equivalent_marker_is_detected() -> None:
    fresh = _doc(
        BODY.replace(MSOFFCRYPTO_0112, MSOFFCRYPTO_0137).replace("6.1.0", "6.1.1")
    )
    assert diff_requirements(_doc(), fresh)


def test_hash_change_is_detected() -> None:
    fresh = _doc(BODY.replace("sha256:bbbb", "sha256:eeee"))
    assert diff_requirements(_doc(), fresh)


def test_hash_removed_is_detected() -> None:
    fresh = _doc(BODY.replace("    --hash=sha256:cccc\n", ""))
    assert diff_requirements(_doc(), fresh)


def test_hash_added_is_detected() -> None:
    fresh = _doc(
        BODY.replace(
            "    --hash=sha256:dddd\n",
            "    --hash=sha256:dddd \\\n    --hash=sha256:ffff\n",
        )
    )
    assert diff_requirements(_doc(), fresh)


def test_package_renamed_or_added_or_removed_is_detected() -> None:
    assert diff_requirements(_doc(), _doc(BODY.replace("alpha==", "alpha2==")))
    assert diff_requirements(
        _doc(), _doc(BODY + "zeta==1.0 \\\n    --hash=sha256:9999\n")
    )
    assert diff_requirements(
        _doc(BODY + "zeta==1.0 \\\n    --hash=sha256:9999\n"), _doc()
    )


def test_semantically_different_marker_is_detected() -> None:
    fresh = _doc(
        BODY.replace("sys_platform == 'win32' \\", "sys_platform != 'win32' \\", 1)
    )
    assert diff_requirements(_doc(), fresh)


def test_marker_dropped_or_added_is_detected() -> None:
    assert diff_requirements(
        _doc(),
        _doc(
            BODY.replace("pywin32==311 ; sys_platform == 'win32' \\", "pywin32==311 \\")
        ),
    )
    assert diff_requirements(
        _doc(),
        _doc(
            BODY.replace("alpha==1.0.0 \\", "alpha==1.0.0 ; sys_platform == 'win32' \\")
        ),
    )


def test_via_comment_change_is_detected() -> None:
    assert diff_requirements(_doc(), _doc(BODY.replace("# via beta", "# via delta")))


def test_committed_requirements_survive_the_measured_uv_013_rewrite() -> None:
    """Real file: the uv 0.13 form of the msoffcrypto marker is accepted, a real change is not."""
    committed = (REPO_ROOT / "requirements.txt").read_text(encoding="utf-8")
    if MSOFFCRYPTO_0112 not in committed:
        pytest.skip("msoffcrypto-tool marker no longer present in requirements.txt")
    rewritten = committed.replace(MSOFFCRYPTO_0112, MSOFFCRYPTO_0137)
    assert rewritten != committed
    assert diff_requirements(committed, rewritten) == []
    assert diff_requirements(
        committed,
        rewritten.replace("msoffcrypto-tool==6.1.0", "msoffcrypto-tool==6.1.1"),
    )


# --------------------------------------------------------------------------- pylock.toml body


def _pylock(marker: str, version: str = "6.1.0", sha: str = "cccc") -> list[str]:
    return [
        "[[packages]]",
        'name = "msoffcrypto-tool"',
        f'version = "{version}"',
        f'marker = "{marker}"',
        f'sdist = {{ hashes = {{ sha256 = "{sha}" }} }}',
    ]


def test_pylock_identical_bodies_have_no_diff() -> None:
    assert (
        diff_pylock_bodies(_pylock(MSOFFCRYPTO_0112), _pylock(MSOFFCRYPTO_0112)) == []
    )


def test_pylock_equivalent_marker_rewrite_is_tolerated() -> None:
    assert (
        diff_pylock_bodies(_pylock(MSOFFCRYPTO_0112), _pylock(MSOFFCRYPTO_0137)) == []
    )


def test_pylock_non_equivalent_marker_is_detected() -> None:
    assert diff_pylock_bodies(
        _pylock(MSOFFCRYPTO_0112), _pylock("sys_platform == 'win32'")
    )


def test_pylock_version_and_hash_changes_are_detected() -> None:
    base = _pylock(MSOFFCRYPTO_0112)
    assert diff_pylock_bodies(base, _pylock(MSOFFCRYPTO_0112, version="6.1.1"))
    assert diff_pylock_bodies(base, _pylock(MSOFFCRYPTO_0112, sha="dddd"))
    # version change hidden behind an equivalent marker rewrite
    assert diff_pylock_bodies(base, _pylock(MSOFFCRYPTO_0137, version="6.1.1"))


def test_pylock_length_change_is_detected() -> None:
    base = _pylock(MSOFFCRYPTO_0112)
    assert diff_pylock_bodies(base, base + ["[[packages]]"])
    assert diff_pylock_bodies(base + ["[[packages]]"], base)


def test_fail_closed_does_not_reject_genuinely_equivalent_pairs() -> None:
    """B1: the fail-closed rule targets `in`/ordering on string variables only."""
    assert markers_equivalent(MSOFFCRYPTO_0112, MSOFFCRYPTO_0137)
    assert markers_equivalent(
        "python_version >= '3.10'",
        "python_version >= '3.10' and python_version >= '3.10'",
    )
    assert markers_equivalent(
        "python_full_version >= '3.10.0'", "python_full_version >= '3.10'"
    )
    assert markers_equivalent("sys_platform == 'win32'", 'sys_platform == "win32"')


@pytest.mark.parametrize(
    ("a", "b"),
    [
        # `===` is arbitrary string equality (PEP 440): it differs from `==` on '3.10.0' vs '3.10'.
        ("python_full_version === '3.10'", "python_full_version == '3.10'"),
        ("python_full_version == '3.10'", "python_full_version === '3.10'"),
        ("'3.10' === python_full_version", "python_full_version == '3.10'"),
    ],
)
def test_triple_equals_is_never_proven_equivalent_to_double_equals(
    a: str, b: str
) -> None:
    assert not markers_equivalent(a, b)
