"""Compare ``uv export`` requirements text across uv versions (#2228).

``requirements.txt`` is regenerated with the uv declared in ``.github/uv-version``, but a dev may
run another uv. Across uv 0.11.2 and 0.13.7 only the header path and the *spelling* of one
environment marker differ (uv 0.13 simplifies it algebraically). The comparison is therefore:

* package, version, hashes, comments and ordering: **exact**;
* environment markers: **semantic equivalence**, evaluated with ``packaging.markers.Marker``
  over the cartesian product of the values observed for every marker variable used by either
  expression (plus an "other" value per variable, so ``!=`` against unlisted values is covered).

Nothing else is loosened: a different package, version, hash or a semantically different marker
is reported.
"""

from __future__ import annotations

import itertools
import re

from packaging.markers import (
    InvalidMarker,
    Marker,
    UndefinedComparison,
    UndefinedEnvironmentName,
)
from packaging.version import InvalidVersion, Version

# PEP 508 marker variables.
_MARKER_VARS = (
    "implementation_name",
    "implementation_version",
    "os_name",
    "platform_machine",
    "platform_python_implementation",
    "platform_release",
    "platform_system",
    "platform_version",
    "python_full_version",
    "python_version",
    "sys_platform",
    "extra",
)
_VERSION_VARS = frozenset(
    {"implementation_version", "python_full_version", "python_version"}
)
# These carry a patch level (3.9.5 is > 3.9 but < 3.10); python_version is always X.Y.
_PATCH_LEVEL_VARS = frozenset({"implementation_version", "python_full_version"})
_VAR_ALT = "|".join(sorted(_MARKER_VARS, key=len, reverse=True))
_OP = r"(?:===|==|!=|<=|>=|~=|<|>|in|not in)"
_LIT = r"""(?:'([^']*)'|"([^"]*)")"""
_VAR_FIRST = re.compile(rf"\b({_VAR_ALT})\s*{_OP}\s*{_LIT}")
_LIT_FIRST = re.compile(rf"{_LIT}\s*{_OP}\s*\b({_VAR_ALT})\b")
_OTHER = "__other__"
_MAX_COMBINATIONS = 200_000


def normalize_uv_export_text(text: str) -> str:
    """Normalize uv export output for stable comparison (header path, optional --frozen)."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.splitlines()
    if len(lines) >= 2 and lines[0].startswith("# This file was autogenerated by uv"):
        lines[1] = "#    uv export --frozen --no-emit-project -o requirements.txt"
    return "\n".join(lines) + "\n"


def _observed_values(*exprs: str) -> dict[str, set[str]]:
    seen: dict[str, set[str]] = {}
    for expr in exprs:
        for m in _VAR_FIRST.finditer(expr):
            seen.setdefault(m.group(1), set()).add(m.group(2) or m.group(3) or "")
        for m in _LIT_FIRST.finditer(expr):
            seen.setdefault(m.group(3), set()).add(m.group(1) or m.group(2) or "")
    return seen


def _version_neighbours(literal: str) -> set[str]:
    """Literal plus the next/previous value of its last component (keeps boundaries visible)."""
    out = {literal}
    try:
        release = list(Version(literal).release)
    except InvalidVersion:
        return out
    for delta in (-1, 1):
        probe = release.copy()
        probe[-1] += delta
        if probe[-1] >= 0:
            out.add(".".join(str(p) for p in probe))
    return out


def _candidates(var: str, literals: set[str]) -> list[str]:
    if var in _VERSION_VARS:
        values = {"0", "9999"}
        for literal in literals:
            for near in _version_neighbours(literal):
                values.add(near)
                if var in _PATCH_LEVEL_VARS:
                    values.add(
                        f"{near}.0.1"
                    )  # just above `near`, below the next component
        return sorted(values)
    return sorted(literals | {_OTHER})


_UNPROVABLE_VAR_FIRST = re.compile(
    rf"\b({_VAR_ALT})\s*(not in|in|===|~=|<=|>=|<|>)\s*{_LIT}"
)
_UNPROVABLE_LIT_FIRST = re.compile(
    rf"{_LIT}\s*(not in|in|===|~=|<=|>=|<|>)\s*\b({_VAR_ALT})\b"
)


def _provable(expr: str) -> bool:
    """False when the candidate set cannot decide the expression (fail closed).

    ``in`` / ``not in`` are substring tests, and ordering operators on non-version variables
    (``platform_release`` ...) are lexicographic; neither is covered by the candidate values.
    """
    for m in _UNPROVABLE_VAR_FIRST.finditer(expr):
        if m.group(2) in ("in", "not in") or m.group(1) not in _VERSION_VARS:
            return False
    for m in _UNPROVABLE_LIT_FIRST.finditer(expr):
        if m.group(3) in ("in", "not in") or m.group(4) not in _VERSION_VARS:
            return False
    return True


def markers_equivalent(a: str, b: str) -> bool:
    """True when both marker expressions give the same result in every observed environment."""
    a, b = a.strip(), b.strip()
    if a == b:
        return True
    try:
        marker_a, marker_b = Marker(a), Marker(b)
    except InvalidMarker:
        return False

    if not (_provable(a) and _provable(b)):
        return False
    used = _observed_values(a, b)
    for var in _MARKER_VARS:
        if re.search(rf"\b{var}\b", a) or re.search(rf"\b{var}\b", b):
            used.setdefault(var, set())
    names = sorted(used)
    pools = [_candidates(name, used[name]) for name in names]

    total = 1
    for pool in pools:
        total *= len(pool)
    if total > _MAX_COMBINATIONS:
        return False  # too large to prove equivalent: fail closed

    for combo in itertools.product(*pools):
        env = dict(zip(names, combo, strict=True))
        env.setdefault("extra", "")
        try:
            if marker_a.evaluate(env) != marker_b.evaluate(env):
                return False
        except (UndefinedComparison, UndefinedEnvironmentName, InvalidVersion):
            return False
    return True


def _split_head(line: str) -> tuple[str, str | None, bool] | None:
    """``name==ver ; marker \\`` -> (spec, marker or None, trailing backslash); None for non-heads."""
    if not line or line[0].isspace() or line.startswith("#"):
        return None
    body = line.rstrip()
    continued = body.endswith("\\")
    if continued:
        body = body[:-1].rstrip()
    spec, sep, marker = body.partition(";")
    return spec.strip(), (marker.strip() if sep else None), continued


def diff_requirements(committed: str, fresh: str) -> list[str]:
    """Differences that matter between two ``uv export`` texts; empty when they are equivalent."""
    left = normalize_uv_export_text(committed).splitlines()
    right = normalize_uv_export_text(fresh).splitlines()
    problems: list[str] = []
    for no, (a, b) in enumerate(itertools.zip_longest(left, right), start=1):
        if a == b:
            continue
        if a is None or b is None:
            problems.append(
                f"line {no}: only in {'fresh' if a is None else 'committed'}: {(a or b)!r}"
            )
            continue
        head_a, head_b = _split_head(a), _split_head(b)
        if head_a and head_b:
            spec_a, marker_a, cont_a = head_a
            spec_b, marker_b, cont_b = head_b
            if (
                spec_a == spec_b
                and cont_a == cont_b
                and marker_a is not None
                and marker_b is not None
                and markers_equivalent(marker_a, marker_b)
            ):
                continue
        problems.append(f"line {no}: committed {a!r} != fresh {b!r}")
    return problems


_PYLOCK_MARKER = re.compile(
    r'^(?P<key>\s*marker\s*=\s*)"(?P<expr>(?:[^"\\]|\\.)*)"\s*$'
)


def diff_pylock_bodies(committed: list[str], fresh: list[str]) -> list[str]:
    """Differences between two ``pylock.toml`` bodies (header already stripped).

    Every line is compared exactly except ``marker = "..."`` values, compared by semantic
    equivalence (see ``markers_equivalent``).
    """
    problems: list[str] = []
    for no, (a, b) in enumerate(itertools.zip_longest(committed, fresh), start=1):
        if a == b:
            continue
        if a is None or b is None:
            problems.append(
                f"line {no}: only in {'fresh' if a is None else 'committed'}: {(a or b)!r}"
            )
            continue
        ma, mb = _PYLOCK_MARKER.match(a), _PYLOCK_MARKER.match(b)
        if (
            ma
            and mb
            and ma["key"] == mb["key"]
            and markers_equivalent(ma["expr"], mb["expr"])
        ):
            continue
        problems.append(f"line {no}: committed {a!r} != fresh {b!r}")
    return problems
